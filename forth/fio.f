// fio.f — ввод ФИО и даты рождения, вывод одной строкой
// Загрузка: console_forth.exe heap.f strings.f fio.f

VAR tbuf  VAR tlen

// СТРОКА ( -- s )
//   Читает строку с клавиатуры через EXPECT,
//   возвращает counted-строку в куче: [len][символы][0]
: СТРОКА
  255 HALLOC tbuf !
  tbuf @ 1+ DUP 254 EXPECT
  STRLENZ tlen !
  tlen @ tbuf @ B!              // buf[0] = длина
  tbuf @ tlen @ + 1+ 0 SWAP B!  // buf[len+1] = 0 (терминатор)
  tbuf @ ;

// ПРОБЕЛ ( -- s )  counted-строка из одного пробела
STR"  " CONST ПРОБЕЛ

// Переменные для хранения строк
VAR фам  VAR им  VAR отч  VAR дат

// Ввод данных
S" Фамилия: " $. СТРОКА фам ! CR
S" Имя: " $. СТРОКА им ! CR
S" Отчество: " $. СТРОКА отч ! CR
S" Дата рождения: " $. СТРОКА дат ! CR

// Сборка и печать в одну строку
VAR Результат
фам @ ПРОБЕЛ S+ им @ S+ ПРОБЕЛ S+ отч @ S+ ПРОБЕЛ S+ дат @ S+ Результат !

